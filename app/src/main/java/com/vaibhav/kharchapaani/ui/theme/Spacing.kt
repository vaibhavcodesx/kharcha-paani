package com.vaibhav.kharchapaani.ui.theme

import androidx.compose.ui.unit.dp

/**
 * One spacing scale on a 4dp base. Related things sit close ([xs]/[s]); separate things get room
 * ([l]/[xl]); sections breathe ([xxl]). Replaces the ad-hoc 6/10/14/18dp values.
 */
object Spacing {
    val xxs = 2.dp
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val l = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
    val xxxl = 48.dp

    /** Horizontal page margin. */
    val page = 20.dp
}
