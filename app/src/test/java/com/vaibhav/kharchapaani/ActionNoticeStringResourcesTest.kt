import kotlinx.coroutines.*
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.test.*
import org.junit.*
import org.junit.Assert.*
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@OptIn(ExperimentalCoroutinesApi::class)
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36])
class ActionNoticeStringResourcesTest {
    private val app = ApplicationProvider.getApplicationContext<Application>()
    private val dispatcher = StandardTestDispatcher()
    private val screen = CoroutineScope(SupervisorJob() + dispatcher)
    private val store = ViewModelStore()
    private lateinit var db: AppDatabase
    private lateinit var vm: MainViewModel

    @Before fun setUp(): Unit = runBlocking {
        Dispatchers.setMain(dispatcher)
        WorkManagerTestInitHelper.initializeTestWorkManager(app, Configuration.Builder().setExecutor(SynchronousExecutor()).build())
        db = Room.inMemoryDatabaseBuilder(app, AppDatabase::class.java).allowMainThreadQueries().build()
        db.personDao().insertPerson(PersonEntity(id = 2, name = "Rohan", avatarColor = "#70C1FF"))
        vm = MainViewModel(app, db, "11111111-2222-3333-4444-555555555555")
        store.put("main", vm)
        screen.launch { vm.people.collect {} }
        until { vm.people.value.any { it.id == 2L } }
    }
    private suspend fun until(condition: () -> Boolean) = withTimeout(10000) {
        while (!condition()) { dispatcher.scheduler.runCurrent(); delay(10) }
    }
    @After fun tearDown(): Unit = runBlocking {
        screen.cancel()
        val job = vm.viewModelScope.coroutineContext[Job]!!
        store.clear(); until { job.isCompleted }
        db.close(); Dispatchers.resetMain()
    }
    @Test fun `action notices preserve user names without changing stored data`(): Unit = runBlocking {
        assertEquals("a groupmate", app.getString(R.string.action_notice_groupmate))
        val name = "Goa's 50% trip"
        vm.createNewGroup(name, "", "🏖️", "#70C1FF", listOf(2L))
        until { vm.submitting.value.isEmpty() }
        assertEquals("Created Goa's 50% trip.", vm.statusMessage.value)
        assertEquals(name, db.groupDao().getAllGroupsDirect().single().name)
        vm.addNewFriend("Rohan", "#70C1FF")
        until { vm.statusMessage.value?.startsWith("You already have") == true && vm.submitting.value.isEmpty() }
        assertEquals("You already have a friend called Rohan. Add something to tell them apart, like an initial.", vm.statusMessage.value)
        assertEquals(1, db.personDao().getAllPeopleDirect().size)
    }
}
